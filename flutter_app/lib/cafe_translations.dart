String translateCafeText(String code, String text) {
  if(code=='en')return text;
  final dictionary=cafeTranslations[code];
  if(dictionary==null)return text;
  final exact=dictionary[text];
  if(exact!=null)return exact;
  final amount=RegExp(r'^(Total|Paid|Remaining|Order total): ([0-9]+) IQD$').firstMatch(text);
  if(amount!=null) {
    const labels={
      'ar':{'Total':'الإجمالي','Paid':'المدفوع','Remaining':'المتبقي','Order total':'إجمالي الطلب'},
      'ku':{'Total':'کۆم','Paid':'هاتیە دان','Remaining':'مایی','Order total':'کۆما داخوازێ'},
    };
    return '${labels[code]![amount[1]]}: ${amount[2]} ${code=='ar'?'دينار عراقي':'دینارێ عیراقی'}';
  }
  if(text.startsWith('Back to '))return '${dictionary['Back']} — ${dictionary[text.substring(8)] ?? text.substring(8)}';
  return text;
}
